#!/usr/bin/env python3
"""Ask a local vision-language model for a safe GrapePick force interval."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path

import torch
from PIL import Image
from transformers import AutoProcessor, Qwen3VLForConditionalGeneration


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_json_object(text: str) -> dict:
    fenced = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, flags=re.DOTALL)
    candidate = fenced.group(1) if fenced else None
    if candidate is None:
        start = text.find("{")
        end = text.rfind("}")
        if start >= 0 and end > start:
            candidate = text[start : end + 1]
    if candidate is None:
        raise ValueError(f"VLM response contains no JSON object: {text!r}")
    value = json.loads(candidate)
    if not isinstance(value, dict):
        raise ValueError("VLM response must decode to a JSON object.")
    return value


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--image", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--max-new-tokens", type=int, default=256)
    parser.add_argument("--detach-range", type=float, nargs=2, default=(2.8, 3.4))
    parser.add_argument("--damage-range", type=float, nargs=2, default=(3.4, 5.0))
    parser.add_argument("--minimum-grip-force", type=float, default=2.8)
    parser.add_argument("--safety-margin", type=float, default=0.1)
    parser.add_argument("--baseline-peak-force", type=float, default=3.52)
    parser.add_argument("--baseline-success-rate", type=float, default=0.68)
    args = parser.parse_args()

    detach_low, detach_high = map(float, args.detach_range)
    damage_low, damage_high = map(float, args.damage_range)
    safe_upper = damage_low - float(args.safety_margin)
    if not (0.0 < detach_low < detach_high and 0.0 < damage_low < damage_high):
        raise ValueError("Force ranges must be positive and strictly increasing.")
    if not (0.0 < args.minimum_grip_force < safe_upper):
        raise ValueError("The minimum grip force must be below the safe upper bound.")

    prompt = f"""You are the force-range advisor for a simulated robotic grape-picking task.
Inspect the supplied frame to verify that the end effector is horizontally grasping one hanging grape.
The controller measures the maximum of the left and right pad-normal loads as grip force.
The hidden stem detachment threshold is randomized uniformly from {detach_low:.2f} to {detach_high:.2f} N.
The hidden grape damage threshold is randomized uniformly from {damage_low:.2f} to {damage_high:.2f} N.
Stem tension is generated by downward pull and is not the same as pad grip force.
The tactile BC baseline peaks near {args.baseline_peak_force:.2f} N and achieved {100.0 * args.baseline_success_rate:.1f}%, with both crushed and no-detach failures.
Recommend a conservative closed-loop pad-force interval. Both endpoints must be at least {args.minimum_grip_force:.2f} N to
maintain frictional contact, and the upper endpoint must be at most {safe_upper:.2f} N to leave at least {args.safety_margin:.2f} N
margin below the minimum {damage_low:.2f} N damage threshold. Tough stems should be handled by extra downward pull,
not by exceeding the safe grip interval.

Return exactly one JSON object and no markdown:
{{"scene_assessment":"...", "force_range_n":[LOW,HIGH], "rationale":"..."}}
"""
    model_path = args.model.resolve()
    image_path = args.image.resolve()
    processor = AutoProcessor.from_pretrained(model_path, local_files_only=True)
    model = Qwen3VLForConditionalGeneration.from_pretrained(
        model_path,
        dtype=torch.bfloat16,
        device_map="cuda",
        local_files_only=True,
    ).eval()
    image = Image.open(image_path).convert("RGB")
    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image", "image": image},
                {"type": "text", "text": prompt},
            ],
        }
    ]
    inputs = processor.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=True,
        return_dict=True,
        return_tensors="pt",
    ).to(model.device)
    with torch.inference_mode():
        generated = model.generate(
            **inputs,
            max_new_tokens=args.max_new_tokens,
            do_sample=False,
        )
    completion = generated[:, inputs["input_ids"].shape[1] :]
    response = processor.batch_decode(completion, skip_special_tokens=True)[0].strip()
    parsed = parse_json_object(response)
    force_range = parsed.get("force_range_n")
    if not isinstance(force_range, list) or len(force_range) != 2:
        raise ValueError(f"Invalid force_range_n in VLM response: {response}")
    low, high = map(float, force_range)
    if not (args.minimum_grip_force <= low < high <= safe_upper):
        raise ValueError(f"Unsafe VLM force range {[low, high]} in response: {response}")

    result = {
        "advisor": "Qwen3-VL-4B-Instruct",
        "advisor_is_real_vlm": True,
        "model_path": str(model_path),
        "image": str(image_path),
        "image_sha256": sha256_file(image_path),
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "prompt": prompt,
        "raw_response": response,
        "scene_assessment": parsed.get("scene_assessment", ""),
        "force_range_n": [low, high],
        "rationale": parsed.get("rationale", ""),
        "task_force_ranges_n": {
            "stem_detachment": [detach_low, detach_high],
            "grape_damage": [damage_low, damage_high],
        },
        "minimum_grip_force_n": args.minimum_grip_force,
        "safety_margin_n": args.safety_margin,
        "hard_validation": (
            f"{args.minimum_grip_force:.2f} <= low < high <= {safe_upper:.2f} N"
        ),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
